"""Talking Machines — export the line's PLC programs as ONE program for OpenPLC Runtime.

  python openplc_export.py --seed 7

writes
  data/openplc/talking_machines.st   upload this in OpenPLC (Programs → Upload Program), then Start PLC
  data/openplc/map.json              which Modbus register holds which tag (the plant model and collector use it)

How the program is laid out (the usual OpenPLC way):
  * every tag lives in a 16-bit register; real numbers are sent as scaled integers (vibration 4.37 mm/s → 437),
    which is how many real PLCs expose analogue values
  * the PLC's OUTPUTS (running, fault, speed, ...: what its logic decides) are %QW0, %QW1, ...
    = Modbus holding registers 0, 1, ...
  * the field INPUTS (sensors: vibration, motor current, temperatures, counters, ...) are %MW0, %MW1, ...
    = Modbus holding registers 1024, 1025, ... The plant model writes them, like an I/O module would.
  * the logic in the middle is exactly the code in plc_programs.py (only the tag names become valid
    identifiers: DB102.DBD24 → DB102_DBD24, B3:3/0 → B3_3_0), so the faults are raised by OpenPLC's own timers.
"""

import argparse
import json
import os
import re

import plc_programs
import simulator

MW_BASE = 1024  # OpenPLC: %MW0 is Modbus holding register 1024
CLOCK = 2  # %MW0-%MW1 hold the plant's clock (seconds since 09:00), set by the plant model
SCALE = {
    "running": 1,
    "fault": 1,
    "gripper_closed": 1,
    "zone_occupied": 1,
    "speed": 10,
    "count": 1,
    "motor_current": 100,
    "motor_temp": 100,
    "vibration": 100,
    "fill_pressure": 1000,
    "cap_torque": 1000,
    "glue_temp": 100,
    "case_count": 1,
    "layer_count": 1,
    "cycle_count": 1,
    "tcp_speed": 10,
    "speed_override": 10,
}
FIELD_ALWAYS = {("cobot", "running"), ("cobot", "fault")}  # the robot controller reports these itself


def ident(tag):
    """A PLC tag as a valid IEC 61131-3 identifier."""
    s = re.sub(r"[^A-Za-z0-9]", "_", tag)
    return re.sub(r"_+", "_", s).strip("_")


def scale_of(signal):
    return SCALE.get(signal, 100 if signal.endswith("_torque") else 100)


def outputs():
    """(machine, signal) pairs the PLC logic writes = PLC outputs."""
    out = set()
    for code in plc_programs.PROGRAMS.values():
        for m, s in re.findall(r"\{(\w+)\.(\w+)\}\s*:=", code):
            out.add((m, s))
    return out - FIELD_ALWAYS


def build(seed, mw_base=MW_BASE):
    import random

    tags = simulator.make_tags(random.Random(seed), seed)
    outs = outputs()
    order = sorted(tags, key=lambda k: (simulator.MACHINES.index(k[0]) if k[0] in simulator.MACHINES else 9, k[1]))
    regmap, qw, mw = {"__clock__": {"addr": mw_base, "type": "uint32"}}, 0, CLOCK
    for key in order:
        v = tags[key]
        is_bool = v["kind"] == "bool"
        entry = {
            "type": "bool" if is_bool else "int16",
            "scale": 1 if is_bool else scale_of(key[1]),
            "dir": "out" if key in outs else "in",
            "ident": ident(v["tag"]),
            "machine": key[0],
            "signal": key[1],
            "kind": v["kind"],
        }
        if entry["dir"] == "out":
            entry["addr"], entry["loc"] = qw, f"%QW{qw}"
            qw += 1
        else:
            entry["addr"], entry["loc"] = mw_base + mw, f"%MW{mw}"
            mw += 1
        regmap[v["tag"]] = entry
    regmap["JAM_CLEARED"] = {
        "type": "bool",
        "scale": 1,
        "dir": "in",
        "ident": "JAM_CLEARED",
        "machine": "capper",
        "signal": "jam_cleared",
        "kind": "bool",
        "addr": mw_base + mw,
        "loc": f"%MW{mw}",
        "internal": True,
    }
    return tags, regmap


def program_text(tags, regmap):
    lines = [
        "(* Talking Machines bottling line: all six controllers in one OpenPLC program.",
        "   Generated by openplc_export.py. Outputs = %QW (holding registers 0..), field inputs = %MW",
        "   (holding registers 1024..). Real values are scaled integers; see map.json. *)",
        "PROGRAM talking_machines",
        "  VAR",
        "    PLANT_CLOCK_HI AT %MW0 : UINT;   (* the plant's clock, so the collector can timestamp rows *)",
        "    PLANT_CLOCK_LO AT %MW1 : UINT;",
    ]
    for t, e in regmap.items():
        if t.startswith("__"):
            continue
        lines.append(f"    {e['ident']}_raw AT {e['loc']} : INT;")
    for t, e in regmap.items():
        if t.startswith("__"):
            continue
        typ = {"bool": "BOOL", "int": "INT", "real": "REAL"}[e["kind"]]
        lines.append(f"    {e['ident']} : {typ};")
    lines += [
        "    TON_VIB : TON;",
        "    TON_JAM : TON;",
        "  END_VAR",
        "",
        "  (* field inputs: scaled registers -> engineering values *)",
    ]
    for t, e in regmap.items():
        if t.startswith("__") or e["dir"] != "in":
            continue
        if e["kind"] == "bool":
            lines.append(f"  {e['ident']} := {e['ident']}_raw <> 0;")
        elif e["kind"] == "int":
            lines.append(f"  {e['ident']} := {e['ident']}_raw;")
        else:
            lines.append(f"  {e['ident']} := INT_TO_REAL({e['ident']}_raw) / {e['scale']:.1f};")
    lines += ["", "  (* the machines' control logic: the same code as data/plc_programs/*.st *)"]
    name = {v["tag"]: regmap[v["tag"]]["ident"] for v in tags.values()}
    for machine, code in plc_programs.PROGRAMS.items():
        body = re.sub(r"\{(\w+)\.(\w+)\}", lambda m: name[tags[(m.group(1), m.group(2))]["tag"]], code)
        body = re.sub(r"[ \t]*\(\*.*?\*\)", "", body).strip()
        lines.append(f"  (* {machine} *)")
        lines += ["  " + l for l in body.splitlines()]
    lines += ["", "  (* PLC outputs: engineering values -> scaled registers *)"]
    for t, e in regmap.items():
        if t.startswith("__") or e["dir"] != "out":
            continue
        if e["kind"] == "bool":
            lines.append(f"  {e['ident']}_raw := BOOL_TO_INT({e['ident']});")
        elif e["kind"] == "int":
            lines.append(f"  {e['ident']}_raw := {e['ident']};")
        else:
            lines.append(f"  {e['ident']}_raw := REAL_TO_INT({e['ident']} * {e['scale']:.1f});")
    lines += [
        "END_PROGRAM",
        "",
        "",
        "CONFIGURATION Config0",
        "  RESOURCE Res0 ON PLC",
        "    TASK task0(INTERVAL := T#100ms,PRIORITY := 0);",
        "    PROGRAM instance0 WITH task0 : talking_machines;",
        "  END_RESOURCE",
        "END_CONFIGURATION",
        "",
    ]
    return "\n".join(lines)


def export(seed, folder="data/openplc", mw_base=MW_BASE):
    os.makedirs(folder, exist_ok=True)
    tags, regmap = build(seed, mw_base)
    with open(os.path.join(folder, "talking_machines.st"), "w", encoding="utf-8") as f:
        f.write(program_text(tags, regmap))
    with open(os.path.join(folder, "map.json"), "w", encoding="utf-8") as f:
        json.dump({"seed": seed, "map": regmap}, f, indent=1)
    return tags, regmap


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument(
        "--mw-base",
        type=int,
        default=MW_BASE,
        help="Modbus address of %%MW0: 1024 in OpenPLC v3; in OpenPLC v4 see the Modbus Server's "
        "Address Mapping Reference",
    )
    a = ap.parse_args()
    tags, regmap = export(a.seed, mw_base=a.mw_base)
    n_out = sum(1 for e in regmap.values() if e.get("dir") == "out")
    n_in = sum(1 for k, e in regmap.items() if e.get("dir") == "in")
    print(
        f"wrote data/openplc/talking_machines.st and data/openplc/map.json for seed {a.seed}: "
        f"{n_out} PLC outputs (%QW, registers 0..), {n_in} field inputs (%MW, registers 1024..)"
    )
